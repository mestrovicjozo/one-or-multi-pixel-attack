def defense_detect_and_fix(img01, topk=1, window=3, neighbor='median'):
    H,W,_ = img01.shape
    w = int(window if window%2==1 else window+1)
    r = w//2
    pad = np.pad(img01, ((r,r),(r,r),(0,0)), mode='reflect')
    scores = np.zeros((H,W), dtype=np.float32)
    for y in range(H):
        for x in range(W):
            patch = pad[y:y+w, x:x+w, :]
            center = img01[y,x,:]
            neigh = patch.reshape(-1,3)
            ref = np.median(neigh, axis=0) if neighbor=='median' else np.mean(neigh, axis=0)
            scores[y,x] = np.linalg.norm(center - ref, ord=2)
    flat_idx = np.argsort(scores.ravel())[::-1][:int(topk)]
    fixed = img01.copy()
    for f in flat_idx:
        y = f // W; x = f % W
        patch = pad[y:y+w, x:x+w, :]
        neigh = patch.reshape(-1,3)
        ref = np.median(neigh, axis=0) if neighbor=='median' else np.mean(neigh, axis=0)
        fixed[y,x,:] = np.clip(ref,0,1)
    return fixed


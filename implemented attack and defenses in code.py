def clamp01(a):
    return np.clip(a, 0.0, 1.0)

def genes_to_coords_colors(genes, k, H=32, W=32):
    # genes: np.ndarray [5*k] u [0,1]
    # coords [(x,y)*k], cols [(r,g,b)*k] u [0,1]
    # Mapa: (x,y) = floor(val * dim), boja = val
    coords, cols = [], []
    for i in range(k):
        gx, gy, rr, gg, bb = genes[5*i:5*(i+1)]
        x = int(np.floor(gx * W)) % W
        y = int(np.floor(gy * H)) % H
        coords.append((x,y))
        cols.append((rr,gg,bb))
    return coords, cols

def apply_genes_to_img01(img01, genes, k):
    # img01: np[H,W,3] u [0,1] (kopira se)
    # genes: [5*k]
    # Vraća novu sliku (pert01) sa zamijenjenim pikselima na apsolutne RGB vrijednosti
    H,W,_ = img01.shape
    pert = img01.copy()
    coords, cols = genes_to_coords_colors(genes, k, H, W)
    for (x,y),(r,g,b) in zip(coords, cols):
        pert[y, x, 0] = r
        pert[y, x, 1] = g
        pert[y, x, 2] = b
    return pert, coords

def to_model_tensor(img01):
    # np[H,W,3] -> torch[1,3,H,W] normirano
    t = torch.from_numpy(img01).permute(2,0,1).float()
    t = transforms.Normalize(mean, std)(t)
    return t.unsqueeze(0)

@torch.no_grad()
def evaluate_population(base01, label, pop, k, targeted=False, target_class=None, batch=64):
    # base01: np[H,W,3] u [0,1]
    # pop: np[pop_size, 5*k]
    # fitness np[pop_size], probs np[pop_size,10], preds np[pop_size], viz_coords list-of-lists
    N = pop.shape[0]
    fitness_list = []
    probs_list = []
    preds_list = []
    coords_list = []
    for s in range(0, N, batch):
        e = min(N, s+batch)
        imgs = []
        chunk_coords = []
        for i in range(s, e):
            imgp, coords = apply_genes_to_img01(base01, pop[i], k)
            chunk_coords.append(coords)
            imgs.append(imgp)
        tt = torch.stack([to_model_tensor(im)[0] for im in imgs]).to(device)
        out = model(tt)
        pr = F.softmax(out, dim=1).detach().cpu().numpy()
        pd = np.argmax(pr, axis=1)
        probs_list.append(pr)
        preds_list.append(pd)
        # fitness
        if targeted:
            assert target_class is not None
            fit = 1.0 - pr[:, target_class]
        else:
            fit = pr[:, label]
        fitness_list.append(fit)
        coords_list.extend(chunk_coords)
    fitness = np.concatenate(fitness_list, axis=0)
    probs = np.concatenate(probs_list, axis=0)
    preds = np.concatenate(preds_list, axis=0)
    return fitness, probs, preds, coords_list

def de_attack(image_tensor, label, k=1, targeted=False, target_class=None,
              pop_size=120, max_iters=120, Fm=0.5, Cr=0.9, seed=None,
              early_stop=True, verbose=True, progress_cb=None):
    """
    image_tensor: torch[3,H,W]
    progress_cb: callback(iter_idx, max_iters, best_fit, eta_seconds) -> None
    """
    if seed is not None:
        random.seed(seed); np.random.seed(seed)

    # Početne info
    with torch.no_grad():
        probs0 = predict_probs(image_tensor.unsqueeze(0))[0].numpy()
    pred0 = int(np.argmax(probs0))
    base01 = tensor_to_img01(image_tensor)  # np[H,W,3] u [0,1]

    if targeted and target_class is None:
        raise ValueError("Za ciljani napad morate zadati target_class.")

    # Inicijalna populacija u [0,1]
    D = 5*k
    pop = np.random.rand(pop_size, D).astype(np.float32)
    fit, pr, pd, coords_list = evaluate_population(base01, label, pop, k, targeted, target_class)

    # helper za progress
    t0 = time.time()
    def _report(it, best_fit_val):
        if progress_cb is None: return
        if it <= 0:
            progress_cb(0, max_iters, best_fit_val if best_fit_val is not None else float('inf'), None)
        else:
            elapsed = time.time() - t0
            eta = (max_iters - it) * (elapsed / it)
            progress_cb(it, max_iters, best_fit_val if best_fit_val is not None else float('inf'), eta)

    # Provjera ranog uspjeha
    def success_mask(preds):
        if targeted:
            return (preds == target_class)
        else:
            return (preds != label)

    smask = success_mask(pd)
    # inicijalni report (0%)
    _report(0, None)

    if early_stop and smask.any():
        i = int(np.where(smask)[0][0])
        imgp, coords = apply_genes_to_img01(base01, pop[i], k)
        # 100% jer smo gotovi
        if progress_cb is not None:
            progress_cb(max_iters, max_iters, float(fit[i]), 0.0)
        return {
            "success": True,
            "best_genes": pop[i].copy(),
            "best_fit": float(fit[i]),
            "iters": 0,
            "result_img01": imgp,
            "coords": coords,
            "probs_before": probs0,
            "probs_after": pr[i],
            "pred_before": pred0,
            "pred_after": int(pd[i])
        }

    # DE petlja
    best_idx = int(np.argmin(fit))
    best = pop[best_idx].copy()
    best_fit = float(fit[best_idx])

    for it in range(1, max_iters+1):
        trial_pop = pop.copy()
        for i in range(pop_size):
            idxs = list(range(pop_size))
            idxs.remove(i)
            a, b, c = np.random.choice(idxs, 3, replace=False)
            mutant = pop[a] + Fm*(pop[b] - pop[c])
            mutant = clamp01(mutant)

            cross_mask = np.random.rand(D) < Cr
            if not cross_mask.any():
                cross_mask[np.random.randint(0,D)] = True
            trial = np.where(cross_mask, mutant, pop[i])
            trial_pop[i] = trial

        # odabir
        tfit, tpr, tpd, tcoords = evaluate_population(base01, label, trial_pop, k, targeted, target_class)
        better = tfit < fit
        pop[better] = trial_pop[better]
        fit[better] = tfit[better]

        # globalni najbolji
        bi = int(np.argmin(fit))
        if fit[bi] < best_fit:
            best_fit = float(fit[bi]); best = pop[bi].copy()

        # progress report (svaku iteraciju)
        _report(it, best_fit)

        # rano zaustavljanje ako je napad uspjesan
        smask = success_mask(tpd)
        if early_stop and smask.any():
            i = int(np.where(smask)[0][0])
            imgp, coords = apply_genes_to_img01(base01, trial_pop[i], k)
            if progress_cb is not None:
                progress_cb(max_iters, max_iters, float(tfit[i]), 0.0)
            return {
                "success": True,
                "best_genes": trial_pop[i].copy(),
                "best_fit": float(tfit[i]),
                "iters": it,
                "result_img01": imgp,
                "coords": coords,
                "probs_before": probs0,
                "probs_after": tpr[i],
                "pred_before": pred0,
                "pred_after": int(tpd[i])
            }

        if verbose and (it % 10 == 0):
            print(f"Iter {it:4d} | best_fit={best_fit:.4f}")

    # ako je neuspjesno vrati najblizi
    imgp, coords = apply_genes_to_img01(base01, best, k)
    with torch.no_grad():
        probs_after = predict_probs(to_model_tensor(imgp))[0].numpy()
    pred_after = int(np.argmax(probs_after))

    if progress_cb is not None:
        progress_cb(max_iters, max_iters, best_fit, 0.0)

    return {
        "success": (pred_after != label) if not targeted else (pred_after == target_class),
        "best_genes": best.copy(),
        "best_fit": best_fit,
        "iters": max_iters,
        "result_img01": imgp,
        "coords": coords,
        "probs_before": probs0,
        "probs_after": probs_after,
        "pred_before": pred0,
        "pred_after": pred_after
    }


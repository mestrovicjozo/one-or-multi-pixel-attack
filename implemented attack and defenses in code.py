# poisson
def _poison_random_pixels(img01, k=1):
    H,W,_ = img01.shape
    out = img01.copy()
    for _ in range(int(k)):
        x = np.random.randint(0, W)
        y = np.random.randint(0, H)
        out[y,x,:] = np.random.rand(3)  # nasumična boja
    return out

class PoisonedCIFAR10PerClass(Dataset):
    """
    Uzimamo točno 'count' primjeraka iz train skupa za 'target_class',
    na svakom pravimo k nasumičnih pixel-otrova (label ostaje isti),
    vraćamo NORMIRANI tensor za model. Sprema i kopije slika za prikaz.
    """
    def __init__(self, root='./data', target_class=0, count=50, k_pixels=1):
        base = datasets.CIFAR10(root=root, train=True, download=True, transform=transforms.ToTensor())
        idxs = [i for i, (_, y) in enumerate(base) if y == target_class]
        if len(idxs) < count:
            raise ValueError(f"Traženo {count} uzoraka za klasu {target_class}, a dostupno je {len(idxs)}.")
        random.shuffle(idxs)
        self.items = []
        self.sample_imgs_np01 = []  # za kasniji prikaz
        for i in idxs[:count]:
            x_t, y = base[i]     # [3,32,32] u [0,1]
            img01 = x_t.permute(1,2,0).numpy()
            poisoned = _poison_random_pixels(img01, k=k_pixels)
            self.sample_imgs_np01.append(poisoned)
            t = torch.from_numpy(poisoned).permute(2,0,1).float()
            t = transforms.Normalize(mean, std)(t)
            self.items.append((t, y))
    def __len__(self): return len(self.items)
    def __getitem__(self, i): return self.items[i]


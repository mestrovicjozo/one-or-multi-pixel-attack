def fmt_eta(sec):
    if sec is None or not np.isfinite(sec):
        return "procjena ETA…"
    sec = max(0, int(sec))
    m, s = divmod(sec, 60)
    if m >= 60:
        h, m = divmod(m, 60)
        return f"~{h:d}h {m:02d}m {s:02d}s"
    return f"~{m:02d}m {s:02d}s"

def run_attack(mode):
    # reset napretka
    prog.value = 0
    prog.bar_style = ''  # reset boje
    status.value = "Pokrećem napad…"
    out_attack.clear_output(wait=True)

    idx = index_slider.value
    x, y = testset[idx]
    k = 1 if mode == 'a' else k_slider.value
    targeted = (mode == 'c')
    tclass = None
    if targeted:
        if target_dd.value.startswith('—'):
            status.value = "<b>Molim odaberite ciljanu klasu.</b>"
            return
        tclass = class_names.index(target_dd.value)

    # callback za napredak iz DE petlje
    def progress_cb(it, max_iters, best_fit, eta_sec):
        pct = int(100 * it / max_iters) if max_iters > 0 else 0
        prog.value = min(max(pct, 0), 100)
        bf = best_fit if np.isfinite(best_fit) else float('inf')
        status.value = f"<b>Iter:</b> {it}/{max_iters} | <b>best_fit:</b> {bf:.4f} | <b>preostalo:</b> {fmt_eta(eta_sec)}"

    # pokreni napad
    res = de_attack(
        image_tensor=x, label=y, k=k, targeted=targeted, target_class=tclass,
        pop_size=pop_size_w.value, max_iters=iters_w.value,
        Fm=F_w.value, Cr=Cr_w.value, seed=seed_w.value,
        early_stop=True, verbose=False, progress_cb=progress_cb
    )

    # Prikaz rezultata
    with out_attack:
        before = tensor_to_img01(x)
        after = res["result_img01"]
        pb = res["probs_before"]; pa = res["probs_after"]
        pred_b = res["pred_before"]; pred_a = res["pred_after"]
        coords = res["coords"]

        fig = plt.figure(figsize=(12,8))
        gs = fig.add_gridspec(2,2)

        ax1 = fig.add_subplot(gs[0,0])
        ax1.imshow(before); ax1.set_title(f"Prije: {class_names[pred_b]} ({pb[pred_b]:.2f})"); ax1.axis('off')
        draw_pixels(ax1, coords, color='r')

        ax2 = fig.add_subplot(gs[0,1])
        ax2.imshow(after); ax2.set_title(f"Nakon: {class_names[pred_a]} ({pa[pred_a]:.2f})"); ax2.axis('off')
        draw_pixels(ax2, coords, color='r')

        ax3 = fig.add_subplot(gs[1,0])
        topk_bar(pb, ax=ax3, title="Vjerojatnosti (prije)")

        ax4 = fig.add_subplot(gs[1,1])
        topk_bar(pa, ax=ax4, title="Vjerojatnosti (nakon)")

        fig.suptitle(f"Uspjeh: {res['success']} | iters={res['iters']} | k={k} | coords={coords}")
        plt.tight_layout()
        plt.show()

        if targeted:
            print(f"Cilj: {target_dd.value} | Postignuto: {class_names[pred_a]}")

    # kraj — postavi 100% i poruku
    prog.value = 100
    prog.bar_style = 'success' if res['success'] else 'warning'
    status.value = f"Gotovo. Uspjeh: <b>{res['success']}</b>."


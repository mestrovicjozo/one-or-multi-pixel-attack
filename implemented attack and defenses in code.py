def _get_predict_probs():
    if "predict_probs" in globals():
        return predict_probs  # očekuje [N,3,H,W] -> [N,C]
    # fallback
    import torch
    import torch.nn.functional as F
    def _fallback_predict_probs(t_batch):
        # t_batch: [N,3,H,W] već normirano mean/std
        dev = globals().get("device", "cpu")
        mdl = globals().get("model", None)
        if mdl is None:
            raise RuntimeError("Model nije definiran u globalima (model).")
        with torch.no_grad():
            out = mdl(t_batch.to(dev))
            return F.softmax(out, dim=1).detach().cpu()
    return _fallback_predict_probs

def _tensor_to_img01_local(t):
    # koristi postojeći helper ako postoji
    if "tensor_to_img01" in globals():
        return tensor_to_img01(t)
    # inače brzi fallback (pretpostavlja globalne mean/std)
    import torch
    x = t.clone().cpu()
    mean_t = torch.tensor(mean).view(3,1,1)
    std_t  = torch.tensor(std).view(3,1,1)
    x = (x * std_t) + mean_t
    x = x.clamp(0,1).permute(1,2,0).numpy()
    return x


@torch.no_grad()
def predict_probs(t):
    # t: [1,3,H,W] normalizirano
    model.eval()
    out = model(t.to(device))
    return softmax(out).detach().cpu()  # [1,10]

def tensor_to_img01(t):
    # t: [3,H,W] normirano -> np[H,W,3] u [0,1]
    x = denorm(t.cpu()).clamp(0,1)
    x = x.permute(1,2,0).numpy()
    return x

def topk_bar(probs, ax=None, k=10, title="Distribucija po klasama"):
    # probs: [10]
    idx = np.argsort(-probs)[:k]
    vals = probs[idx]
    labels = [class_names[i] for i in idx]
    if ax is None:
        fig, ax = plt.subplots(figsize=(7,4))
    ax.bar(range(len(vals)), vals)
    ax.set_xticks(range(len(vals)))
    ax.set_xticklabels(labels, rotation=45, ha='right')
    ax.set_ylim(0,1)
    ax.set_title(title)
    return ax, idx, vals


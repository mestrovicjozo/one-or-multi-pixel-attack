def _to_np01(img):
    """str/tensor/PIL/ndarray -> np.float32 [0,1], shape (H,W,3)"""
    if isinstance(img, np.ndarray):
        arr = img
        if arr.ndim == 3 and arr.shape[0] in (1,3) and arr.shape[0] != arr.shape[-1]:
            arr = np.transpose(arr, (1,2,0))
        if arr.ndim == 2:  # grayscale
            arr = np.repeat(arr[...,None], 3, axis=2)
        arr = arr.astype(np.float32)
        if arr.max() > 1.0: arr = arr / 255.0
        return np.clip(arr, 0, 1)
    if torch.is_tensor(img):
        t = img.detach().cpu()
        if t.ndim == 4: t = t[0]
        if t.ndim == 3 and t.shape[0] in (1,3) and t.shape[0] != t.shape[-1]:
            t = t.permute(1,2,0)
        arr = t.numpy().astype(np.float32)
        if arr.ndim == 2: arr = np.repeat(arr[...,None], 3, axis=2)
        if arr.max() > 1.0: arr = arr / 255.0
        return np.clip(arr, 0, 1)
    if isinstance(img, Image.Image):
        return (np.asarray(img.convert('RGB')).astype(np.float32)/255.0).clip(0,1)
    if isinstance(img, str):
        im = Image.open(img).convert('RGB')
        return (np.asarray(im).astype(np.float32)/255.0).clip(0,1)
    raise TypeError(f"result_img01 nepodržan tip: {type(img)}")


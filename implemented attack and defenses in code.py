def pick_random_correct_not_confident(tau=0.98, max_tries=250, relax=True, used=None):
    """
    Traži indeks gdje je model točan i pmax ≤ tau, izbjegavajući 'used'.
    Ako ne nađe unutar max_tries, relaksira tau (0.99, 0.999) i ponovno pokuša.
    Vraća: (idx, pmax, pred, used_tau) ili (None, None, None, None).
    """
    if used is None:
        used = set()
    N = len(testset)
    taus = [tau] + ([0.99, 0.999] if relax else [])
    predict_fn = _get_predict_probs()

    for tcur in taus:
        perm = np.random.permutation(N)
        checks = 0
        for i in perm:
            if checks >= max_tries:
                break
            idx = int(i)
            if idx in used:
                continue  # ne troši pokušaj na već korištene
            x, y = testset[idx]  # x: [3,32,32] normirano CHW
            pr = predict_fn(x.unsqueeze(0))[0].numpy()
            pred = int(np.argmax(pr))
            pmax = float(pr[pred])
            if (pred == y) and (pmax <= tcur):
                return idx, pmax, pred, tcur
            checks += 1
    return None, None, None, None

